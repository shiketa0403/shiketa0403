#!/bin/bash
set -euo pipefail

# SessionStart hook: 記事作成プロンプト(wp-auto-article/common/01〜10)を
# 自動でcontextにロードする。
#
# 目的: Claudeが記事作成タスクを「common/を読まずに記憶ベースで」走らせる
# 失敗を防ぐ。10本のプロンプトをセッション開始時に強制的にcontextへ。

COMMON_DIR="${CLAUDE_PROJECT_DIR}/wp-auto-article/common"

if [ ! -d "$COMMON_DIR" ]; then
  # common/ が存在しない場合は何も出力せず終了(他リポジトリ転用時の安全策)
  exit 0
fi

cat <<'PREAMBLE'
================================================================================
⚠️ 記事作成タスク 絶対遵守プロンプト(SessionStart hookで自動ロード)
================================================================================

以下は wp-auto-article/common/ にある記事作成プロンプト全文(01〜10)です。
**記事作成リクエスト(キーワード+メディアの指定など)を受けたら、必ずこれらの
内容に厳密に従って作業すること。**

【絶対ルール】
1. 創作禁止: ここに書かれていない出力形式・装飾・構造を独自考案しない
2. 記憶禁止: 「前回こうだった」「別記事ではこうだった」は使用禁止
3. アレンジ禁止: プロンプト内のHTML・ショートコード・bgcolorなどは
   1文字も変えずにそのままコピーする

【各 Step 実行時のプロトコル】
- 各 Step 開始前に、対応する common/0X_*.md を再度 Read する
  (このhookで一度ロード済みだが、長い会話の後半でも参照しやすくするため)
- そのプロンプトに書かれていない出力は一切しない
- 「より良くしたい」と感じた瞬間に作業を止めて、ユーザーに質問する

================================================================================
PREAMBLE

# 01〜10の順に出力
for n in 01 02 03 04 05 06 07 08 09 10; do
  file=$(find "$COMMON_DIR" -maxdepth 1 -name "${n}_*.md" -print -quit)
  if [ -n "$file" ] && [ -f "$file" ]; then
    basename=$(basename "$file")
    echo ""
    echo "================================================================================"
    echo "▼▼▼ $basename ▼▼▼"
    echo "================================================================================"
    cat "$file"
    echo ""
  fi
done

cat <<'REMINDER'

================================================================================
【再確認 — 記事作成リクエストを受けたら必ず守ること】
================================================================================
- 上記10本のプロンプトに書かれていない出力は一切しない
- アレンジ・創作・記憶ベース実行を禁止
- 各 Step 開始時に対応する common/0X_*.md を必ず Read してから着手する
- 不明点があればユーザーに質問する(独自判断で進めない)
- 「装飾を独自設計」「テーブルを追加」「CTAボタンをデザイン」などの
  創作衝動が起きた瞬間に作業停止 → ユーザーに質問する
================================================================================
REMINDER
